def myround(x, base=10):
	"""
	Aids in building the age part for the url for Demographic videos
	
	:param x: Patient age 
	:type: int/str
	"""
	tq= 80
	if x == "G":
		tq = "G"
	elif x < 80 :
                tq= int(base * round(float(x)/base))
	else:
		tq=int(80)
	return tq
    
